#!/usr/bin/env node
// Regenerate changelog.mdx from the GitHub Releases of the breadbox repo.
//
// Single source of truth: the GitHub Releases on canalesb93/breadbox (whose
// bodies come from CHANGELOG.md via release.yml). This script turns each
// published release into one Mintlify <Update> block so the docs changelog can
// never drift from what was actually shipped.
//
// Usage:
//   node scripts/gen-changelog.mjs            # writes ./changelog.mdx
//   node scripts/gen-changelog.mjs --check    # exit 1 if changelog.mdx is stale
//
// Env:
//   REPO      owner/name to read releases from (default canalesb93/breadbox)
//   GH_TOKEN  / GITHUB_TOKEN  optional; raises the API rate limit (CI sets it)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const REPO = process.env.REPO || "canalesb93/breadbox";
const TOKEN = process.env.GH_TOKEN || process.env.GITHUB_TOKEN || "";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "changelog.mdx");
const CHECK = process.argv.includes("--check");

const MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
];

function fmtDate(iso) {
  const d = new Date(iso);
  return `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`;
}

// Drop a leading blockquote (the repeated "Pre-1.0" disclaimer) — it's hoisted
// to a single <Note> at the top of the page instead of repeating per release.
function stripLeadingBlockquote(body) {
  const lines = body.replace(/\r\n/g, "\n").split("\n");
  let i = 0;
  while (i < lines.length && lines[i].trim() === "") i++;
  if (i < lines.length && lines[i].trimStart().startsWith(">")) {
    while (i < lines.length && (lines[i].trimStart().startsWith(">") || lines[i].trim() === "")) i++;
  }
  return lines.slice(i).join("\n").trim();
}

// Drop the trailing "--- / Docker image: ..." footer that release.yml appends
// to every release body — it's pipeline plumbing, not user-facing release notes.
function stripDockerFooter(body) {
  return body.replace(/\n*-{3,}\s*\n+Docker image:[\s\S]*$/, "").trim();
}

function cleanBody(body) {
  return stripDockerFooter(stripLeadingBlockquote(body));
}

async function fetchReleases() {
  const headers = {
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": "breadbox-docs-changelog-sync",
  };
  if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;

  const out = [];
  for (let page = 1; page <= 10; page++) {
    const url = `https://api.github.com/repos/${REPO}/releases?per_page=100&page=${page}`;
    const res = await fetch(url, { headers });
    if (!res.ok) {
      throw new Error(`GitHub API ${res.status} ${res.statusText}: ${await res.text()}`);
    }
    const batch = await res.json();
    out.push(...batch);
    if (batch.length < 100) break;
  }
  return out
    .filter((r) => !r.draft)
    .sort((a, b) => new Date(b.published_at) - new Date(a.published_at));
}

function render(releases) {
  const blocks = releases.map((r) => {
    const label = r.tag_name || r.name || "Release";
    const date = r.published_at ? fmtDate(r.published_at) : "";
    const body = cleanBody(r.body || "");
    const inner = body || "_No release notes._";
    return [
      `<Update label="${label}" description="${date}">`,
      inner,
      `</Update>`,
    ].join("\n");
  });

  return `---
title: "Changelog"
sidebarTitle: "Changelog"
description: "Release notes for every published version of Breadbox."
rss: true
---

{/* GENERATED FILE — do not edit by hand.
    Source of truth: GitHub Releases on ${REPO} (driven by CHANGELOG.md).
    Regenerated by .github/workflows/sync-changelog.yml -> scripts/gen-changelog.mjs.
    To change an entry, edit the GitHub Release (or CHANGELOG.md and re-cut) and
    re-run the workflow. */}

<Note>
  Breadbox is pre-1.0. While on \`0.x\`, minor releases may include breaking changes.
</Note>

${blocks.join("\n\n")}
`;
}

const releases = await fetchReleases();
if (releases.length === 0) {
  console.error("No releases found — refusing to overwrite changelog.mdx.");
  process.exit(1);
}
const next = render(releases);

if (CHECK) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current.trim() !== next.trim()) {
    console.error("changelog.mdx is out of date — run: node scripts/gen-changelog.mjs");
    process.exit(1);
  }
  console.log("changelog.mdx is up to date.");
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote ${OUT} from ${releases.length} release(s).`);
}
